"""Dataset locations and loaders.

Layout for a region ``<id>`` (default ``atlanta-downtown``)::

    backend/datasets/regions/<id>/
        region.json      RegionInfo
        streets.json     street centerlines used as routing corridors (provenance per feature)
        landmarks.json   named public facilities (provenance per feature)
        design.json      illustrative (SIMULATED) utility design interpreted by the generator
        network.json     InfrastructureNetwork  (generated by app.networks.generate)
        scenarios.json   list[ScenarioPreset]   (generated by app.networks.generate)
        demo.json        DemoScript             (generated by app.networks.generate)
    backend/datasets/cache/osm/<id>.json   raw Overpass response cache (app.ingest.overpass)

The generator also mirrors network.json to ``public/demo/network.json`` for the
frontend's offline snapshot mode.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from app.config import REGIONS_DIR, get_settings
from app.models.schemas import DemoScript, InfrastructureNetwork, RegionInfo, ScenarioPreset


def region_dir(region_id: str | None = None) -> Path:
    return REGIONS_DIR / (region_id or get_settings().region_id)


def network_path(region_id: str | None = None) -> Path:
    return region_dir(region_id) / "network.json"


def load_region(region_id: str | None = None) -> RegionInfo:
    return RegionInfo.model_validate_json((region_dir(region_id) / "region.json").read_text())


@lru_cache(maxsize=4)
def load_network(region_id: str | None = None) -> InfrastructureNetwork:
    path = network_path(region_id)
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Generate it with: cd backend && python -m app.networks.generate"
        )
    return InfrastructureNetwork.model_validate_json(path.read_text())


def load_presets(region_id: str | None = None) -> list[ScenarioPreset]:
    path = region_dir(region_id) / "scenarios.json"
    if not path.exists():
        return []
    return [ScenarioPreset.model_validate(p) for p in json.loads(path.read_text())]


def load_demo_script(region_id: str | None = None) -> DemoScript | None:
    path = region_dir(region_id) / "demo.json"
    if not path.exists():
        return None
    return DemoScript.model_validate_json(path.read_text())
